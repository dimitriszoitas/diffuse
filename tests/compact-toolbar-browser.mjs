// Disposable Chromium controller fixture: no user profile or provider requests.
import assert from 'node:assert/strict';
import {readFile,mkdir} from 'node:fs/promises';
import {createRequire} from 'node:module';
import {resolve} from 'node:path';
const require=createRequire(import.meta.url);
const {chromium}=process.env.PLAYWRIGHT_MODULE?require(process.env.PLAYWRIGHT_MODULE):await import('playwright');
const project=resolve(import.meta.dirname,'..'),artifacts=resolve(project,'artifacts/compact-toolbar');
await mkdir(artifacts,{recursive:true});
const browser=await chromium.launch({headless:true,args:['--use-mock-keychain','--password-store=basic']});
try {
  const page=await browser.newPage({viewport:{width:1280,height:900}});
  const errors=[];page.on('pageerror',error=>errors.push(error.message));
  await page.setContent('<!doctype html><title>Compact toolbar fixture</title><style>body{margin:80px;font:16px system-ui;color:#211a35;background:#f8f6fc}main{padding:36px;border:1px solid #ddd2ee;border-radius:16px;background:white;max-width:700px}button{padding:14px}</style><main><h1>Review your latest release</h1><p>A fictional page used to inspect Diffuse controls.</p><button id="target">Create release</button></main>');
  await page.evaluate(()=>{
    const image=document.createElement('canvas');image.width=32;image.height=32;
    window.fixtureDraft={id:'draft',evidence:{production:{dataUrl:image.toDataURL()}}};window.calls=[];
    window.chrome={runtime:{id:'fixture',onMessage:{addListener(fn){window.receiver=fn;}},async sendMessage(message){window.calls.push(message);return message.type==='STOP_RECORDING'?{ok:true,draft:window.fixtureDraft}:{ok:true};}}};
    window.deliver=message=>new Promise(resolve=>window.receiver({namespace:'diffuse',sessionId:'review',...message},{id:'fixture'},resolve));
  });
  for(const file of ['inspector.js','content.js'])await page.addScriptTag({content:await readFile(resolve(project,'extension',file),'utf8')});
  const deliver=message=>page.evaluate(message=>window.deliver(message),message);
  const overlay=page.locator('diffuse-live-overlay');
  const session={id:'review',mode:'comparison',sourceTabId:1,status:'live',settings:{opacity:.55,reveal:50,linked:false},commentCount:1,comments:[{id:'first',fields:{comment:'Check this action',category:'ux-issue'},selection:{selector:'#target'},context:{production:{url:'about:blank',viewportProfile:{key:'laptop'},viewport:{width:1280,height:900}}}}]};
  await deliver({type:'INITIALIZE',role:'target',session});
  const toolbar=overlay.locator('#toolbar');
  const geometry=()=>toolbar.evaluate(node=>{const b=node.getBoundingClientRect();return{left:b.left,right:b.right,height:b.height,overflow:node.scrollWidth-node.clientWidth};});
  const full=await geometry();assert(full.height<=130,`Desktop toolbar should fit two compact rows, got ${full.height}px`);assert.equal(full.overflow,0);
  assert.equal(await overlay.locator('#recording-note').isVisible(),false);
  assert.ok(!(await toolbar.textContent()).includes('Screenshots with every comment'));
  await page.screenshot({path:resolve(artifacts,'expanded-desktop.png')});
  await overlay.locator('#toolbar-toggle').click();
  assert.equal(await toolbar.getAttribute('data-minimized'),'true');
  assert.equal(await overlay.locator('.comment-pin').isVisible(),true);
  assert.equal(await overlay.locator('#comment').isVisible(),false);
  assert.equal(await overlay.locator('#toolbar-toggle').getAttribute('aria-label'),'Expand Diffuse toolbar');
  const mini=await geometry();assert(mini.height<=60&&mini.right-mini.left<=220);
  await page.screenshot({path:resolve(artifacts,'minimized.png')});
  await deliver({type:'SESSION_UPDATE',session:{...session,settings:{...session.settings,opacity:.7}}});
  assert.equal(await toolbar.getAttribute('data-minimized'),'true');
  await deliver({type:'INITIALIZE',role:'target',session});assert.equal(await toolbar.getAttribute('data-minimized'),'true');
  await overlay.locator('#toolbar-toggle').focus();await page.keyboard.press('Enter');
  assert.equal(await toolbar.getAttribute('data-minimized'),'false');
  await overlay.locator('#area-comment').click();await overlay.locator('#toolbar-toggle').click();
  assert.equal(await overlay.locator('#picker-tip').isVisible(),true);
  await overlay.locator('#cancel-picker').click();
  console.log('PASS compact desktop, keyboard expand, current-session persistence, pins and picker survive minimization');
  await deliver({type:'SESSION_UPDATE',session:{...session,recording:{id:'recording',startedAt:Date.now()-2000}}});
  assert.equal(await overlay.locator('#minimized-record').isVisible(),true);
  assert.match(await overlay.locator('#minimized-record').textContent(),/Stop recording · 00:/);
  await page.setViewportSize({width:390,height:844});
  const miniRecording=await geometry();assert(miniRecording.left>=0&&miniRecording.right<=390);assert.equal(miniRecording.overflow,0);
  await page.screenshot({path:resolve(artifacts,'minimized-recording.png')});
  await overlay.locator('#minimized-record').click();
  assert.equal(await page.evaluate(()=>window.calls.filter(item=>item.type==='STOP_RECORDING').length),1);
  assert.equal(await overlay.locator('#comment-panel').isVisible(),true);
  assert.equal(await toolbar.getAttribute('data-minimized'),'true');
  await overlay.locator('#cancel-comment').click();
  await overlay.locator('#toolbar-toggle').click();
  const narrow=await geometry();assert(narrow.left>=0&&narrow.right<=390);assert.equal(narrow.overflow,0);
  const targets=await toolbar.locator('button').evaluateAll(buttons=>buttons.filter(button=>button.checkVisibility()).map(button=>{const b=button.getBoundingClientRect();return{id:button.id,width:b.width,height:b.height};}));
  for(const button of targets)assert(button.width>=44&&button.height>=44,button.id);
  await page.screenshot({path:resolve(artifacts,'expanded-phone.png')});
  await deliver({type:'DOCK_STATE',docked:true});assert.equal(await overlay.locator('#toolbar-toggle').isVisible(),true);
  await overlay.locator('#toolbar-toggle').click();assert.equal(await toolbar.getAttribute('data-minimized'),'true');
  await deliver({type:'PREPARE_EVIDENCE'});assert.equal(await toolbar.isVisible(),false);await deliver({type:'RESTORE_EVIDENCE'});
  assert.equal(await toolbar.isVisible(),true);assert.equal(await toolbar.getAttribute('data-minimized'),'true');
  await deliver({type:'INITIALIZE',role:'target',session:{...session,id:'new-review'}});assert.equal(await toolbar.getAttribute('data-minimized'),'false');
  assert.deepEqual(errors,[]);
  console.log('PASS recording Stop stays reachable, composer remains open, narrow/docked targets fit, evidence hides toolbar, new session resets');
} finally {await browser.close();}
